/**
 * 文字幅 — Phase 3（pdf-lib 撤去）の L1.5。
 *
 * **なぜこの段があるのか。**
 * 引き継ぎ文書 §3.5 は「難所は生きた `PDFDocument.context` への register / lookup で、
 * そこを置き換えるには文書モデル（L2）が要る」と書いている。それは実測どおりだが、
 * **欠落はもう 1 つある**。L2 の器を建てても、そのままではテキストが 1 文字も置けない ——
 * 「この文字列は何 pt 幅か」に答える経路が normativepdf に無いからである（2026-08-14 実測）:
 *
 *   - normativepdf は `dependencies: {}`。メトリクスの概念がコードベースに 1 行も無い
 *   - `buildType0Font` の `Type0FontSpec.widths` は **呼び出し側が用意する入力**である。
 *     `/W`（§9.7.4.3）について仕様が決めるのは「辞書にどう書くか」であって、
 *     グリフが何 unit 進むかは仕様ではなくフォントプログラムが持つ
 *
 * この穴は L3（COS プリミティブ）にも L4（部分系）にも書かれていなかった。
 * 見つけずに L2 へ進むと、器はできたのに `drawText` を外せない状態で止まる。
 *
 * **決定（2026-08-14）: メトリクスは writer の関心に残す。**
 * normativepdf は「仕様が要求する形を書く」自前依存 0 のライブラリで、標準 14 書体の
 * AFM を抱えるとその性格が変わる。一方 writer は既に `@pdf-lib/fontkit` と
 * `subset-font` を直接の依存に持っており、**埋め込みフォントの advance の出所は
 * こちら側にある**。残る穴は標準 14 書体（§9.6.2.2）だけで、埋め込まれない
 * Helvetica 等の幅は今なお pdf-lib の `PDFFont`（`@pdf-lib/standard-fonts` の AFM）
 * から来ている。撤去の最後にここを自前の幅表へ差し替える。
 *
 * **この段で出力は 1 バイトも変わらない。** 下記のとおり `PDFFont` はこの型を
 * *構造的に* 満たすので、アダプタも割り当ても挟まらない。したがって
 * `npm run oracle` は差 0 でなければならず、**差が出たらそれは移行ではなく事故**である。
 *
 * ⚠️ これは pdf-lib → COS の変換層ではない（handoff §6 で作らないと決めたもの）。
 * ここにあるのは型 1 つで、オブジェクトモデルの変換はしていない。
 */

/**
 * 文字列の前進幅を pt で答えるもの。
 *
 * **メソッド名を pdf-lib の `PDFFont` と揃えてあるのは意図的である。**
 * こうしておくと `PDFFont` がこの型を構造的に満たし、変換関数もアダプタも要らない ——
 * つまり移行のこの段は純粋に型の上でだけ起き、実行時の挙動は不変になる。
 * 自前実装へ差し替えるときは、同じ名前のメソッドを 1 つ持つ値を渡せばよい。
 *
 * 幅は「1000 単位のグリフ空間」ではなく **pt** で答える（`/W` に書く値とは単位が違う）。
 * `/W` を組み立てるのは埋め込み時の別の関心で、そちらは `font-manager.ts` が持つ。
 */
export interface TextMetrics {
  widthOfTextAtSize(text: string, size: number): number;
}
